tab_n = [0]


def TABLE(df, caption, index=True, fs=9):
    tab_n[0] += 1
    P(f"Таблица {tab_n[0]} — {caption}", italic=True, size=11)
    d = df.reset_index() if index else df
    tb = doc.add_table(rows=1, cols=len(d.columns))
    tb.style = "Table Grid"
    for i, c in enumerate(d.columns):
        tb.rows[0].cells[i].text = str(c)
    for _, row in d.iterrows():
        cells = tb.add_row().cells
        for i, v in enumerate(row):
            cells[i].text = str(v)
    for row in tb.rows:
        for c in row.cells:
            for p in c.paragraphs:
                for r in p.runs:
                    r.font.size = Pt(fs)
    for c in tb.rows[0].cells:
        for r in c.paragraphs[0].runs:
            r.bold = True
    P()


